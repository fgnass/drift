/**
 * App icon generator
 *
 * Draws the icon: the quiet night of the app (sky, aurora, candlelight,
 * stars) with the wordmark in Economica Italic in the middle. The wordmark
 * comes from the same shaping as in the page (see lettering.mjs), so the
 * icon and the header always match.
 *
 * The SVG is written in two flavors and then rendered with Chromium:
 *
 *   public/icons/icon.svg               full bleed square (manifest, "any")
 *   public/icons/icon-{192,512,1024}.png full bleed square (manifest,
 *                                        "any maskable"; the OS cuts its shape)
 *   public/icons/apple-touch-icon.png   full bleed square (iOS rounds it)
 *   public/favicon.svg                  rounded tile on transparent (browser tab)
 *   public/favicon.ico                  the rounded tile at 16, 32 and 64 px
 *
 * The wordmark stays inside the maskable safe zone (a circle of 40 % of the
 * width around the center), so no launcher cuts into the letters.
 *
 * Re-run after a change here or in the font:  npm run icons
 */
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { shape } from "./lettering.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const publicDir = resolve(root, "public");
const iconsDir = resolve(publicDir, "icons");

// The icon is designed on a 256 × 256 canvas, like the previous one.
const SIZE = 256;
const TILE_RADIUS = 56;
// Width of the wordmark on the canvas. The letters are 0.69 of the width,
// which keeps every corner of the ink inside the maskable safe circle.
const WORDMARK_WIDTH = 176;

const mark = shape("drift");
const scale = WORDMARK_WIDTH / mark.width;
// Center the ink box. With Economica this puts the x-height band of the
// letters almost exactly on the middle line, which is what the eye centers.
const tx = (SIZE - mark.width * scale) / 2 - mark.x * scale;
const ty = (SIZE - mark.height * scale) / 2 - mark.y * scale;

const scene = `
  <defs>
    <linearGradient id="sky" x2="0" y2="1">
      <stop stop-color="#080b12"/>
      <stop offset="1" stop-color="#111927"/>
    </linearGradient>
    <radialGradient id="horizon" cx="70%" cy="100%" r="85%">
      <stop stop-color="#18243b"/><stop offset="1" stop-color="#18243b" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="candle" cx="50%" cy="102%" r="65%">
      <stop stop-color="#ffb060" stop-opacity=".16"/>
      <stop offset=".35" stop-color="#ff8c46" stop-opacity=".072"/>
      <stop offset="1" stop-color="#ff783c" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="aurora" x2="1" y2="0">
      <stop stop-color="#4af0c4" stop-opacity=".16"/>
      <stop offset=".4" stop-color="#9bf7a6" stop-opacity=".3"/>
      <stop offset=".75" stop-color="#4af0c4" stop-opacity=".24"/>
      <stop offset="1" stop-color="#8e6cff" stop-opacity=".18"/>
    </linearGradient>
    <filter id="air" x="-30%" y="-150%" width="160%" height="400%"><feGaussianBlur stdDeviation="12"/></filter>
    <clipPath id="tile"><rect width="${SIZE}" height="${SIZE}" rx="${TILE_RADIUS}"/></clipPath>
  </defs>
  <rect width="${SIZE}" height="${SIZE}" fill="url(#sky)"/>
  <rect width="${SIZE}" height="${SIZE}" fill="url(#horizon)"/>
  <path d="M-30 85 C30 115 66 41 120 66 S199 73 283 33" fill="none" stroke="url(#aurora)" stroke-width="25" filter="url(#air)"/>
  <path d="M-20 109 C51 83 73 109 132 91 S216 48 278 75" fill="none" stroke="#8e6cff" stroke-opacity=".13" stroke-width="16" filter="url(#air)"/>
  <rect width="${SIZE}" height="${SIZE}" fill="url(#candle)"/>
  <g fill="#dbe7f5">
    <circle cx="36" cy="42" r="1.2" opacity=".42"/>
    <circle cx="185" cy="28" r=".8" opacity=".3"/>
    <circle cx="226" cy="87" r="1.5" opacity=".38"/>
    <circle cx="65" cy="103" r="1.1" opacity=".36"/>
    <circle cx="172" cy="157" r="1.4" opacity=".4"/>
    <circle cx="97" cy="178" r="1.5" opacity=".32"/>
    <circle cx="30" cy="167" r="1.6" opacity=".45"/>
    <circle cx="212" cy="202" r="1.1" opacity=".35"/>
    <circle cx="69" cy="231" r="1.3" opacity=".36"/>
    <circle cx="158" cy="220" r=".8" opacity=".28"/>
  </g>
  <!-- The wordmark, the same glyphs as in the header of the app. -->
  <path d="${mark.d}" transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${scale.toFixed(5)})" fill="#f3f4f7"/>
`;

/** The icon as SVG, as a full bleed square or as a rounded tile. */
function svg({ tile }) {
  const body = tile ? `  <g clip-path="url(#tile)">${scene}  </g>\n` : scene;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">\n` +
    `  <!-- drift: quiet night, aurora, candlelight and the wordmark. Generated by scripts/icons.mjs. -->\n` +
    `${body}</svg>\n`
  );
}

/** Packs PNG images into one .ico file (PNG entries, as all browsers read). */
function ico(pngs) {
  const header = Buffer.alloc(6 + pngs.length * 16);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, png }, i) => {
    const e = 6 + i * 16;
    header[e] = size % 256; // 0 means 256
    header[e + 1] = size % 256;
    header.writeUInt16LE(1, e + 4); // color planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(png.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...pngs.map((p) => p.png)]);
}

const square = svg({ tile: false });
const rounded = svg({ tile: true });
await writeFile(resolve(iconsDir, "icon.svg"), square);
await writeFile(resolve(publicDir, "favicon.svg"), rounded);

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE } });

/** Renders the SVG at `size` pixels, transparent where the SVG is. */
async function render(markup, size) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<!doctype html><style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${markup}`,
  );
  return page.screenshot({ type: "png", omitBackground: true });
}

for (const size of [192, 512, 1024]) {
  await writeFile(resolve(iconsDir, `icon-${size}.png`), await render(square, size));
}
await writeFile(resolve(iconsDir, "apple-touch-icon.png"), await render(square, 180));

const favicons = [];
for (const size of [16, 32, 64]) {
  favicons.push({ size, png: await render(rounded, size) });
}
await writeFile(resolve(publicDir, "favicon.ico"), ico(favicons));

await browser.close();
console.log("Icons written to public/ and public/icons/");
